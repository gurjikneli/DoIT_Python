# 1. დაწერეთ პითონის პროგრამა, რომელიც დასაწყისში შექმნის ცარიელ სიას ([]), თუ მომხარებელი შეიყვანს სიმბოლო 'a'-ს,
# ნიშნავს რომ უნდა დაამატოთ სიაში რიცხვი; თუ აკრიფა 'r', სიიდან უნა წაიშალოს რიცხვი; 'e'-ს შეტანისას პროგრამამ უნდა
# დაასრულოს მუშაობა. მიღებული შედეგი დაბეჭდეთ კონსოლში.

# a – append

# r – remove

# e – exit

# გამოიყენეთ მხოლოდ ეს ბრძანებები და მოახდინეთ სიაზე ზემოქმედება.

lst = []
continue_game = True

while continue_game:
    st = input("Enter 'a', 'r' or 'e': ")

    if st == 'a':
        lst.append(100)
    if st == 'r':
        lst.remove(100)
    if st == 'e':
        continue_game = False

print(lst)


